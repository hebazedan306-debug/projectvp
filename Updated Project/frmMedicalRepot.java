    public boolean ValidateData() {

        if (txtChildName.getText().trim().isEmpty()) {
            txtChildName.requestFocus();
            txtChildName.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtChildName.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        if (txtDate.getText().trim().isEmpty()) {
            txtDate.requestFocus();
            txtDate.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtDate.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        if (txtDoctorName.getText().trim().isEmpty()) {
            txtDoctorName.requestFocus();
            txtDoctorName.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtDoctorName.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        if (txtDescription.getText().trim().isEmpty()) {
            txtDescription.requestFocus();
            txtDescription.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtDescription.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        JOptionPane.showMessageDialog(this, "Report Saved Successfully");

        return true;
    }

    public void ClearData() {

        txtChildName.setText("");
        txtDate.setText("");
        txtDoctorName.setText("");
        txtDescription.setText("");
    }

