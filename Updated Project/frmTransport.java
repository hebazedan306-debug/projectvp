    private void btnUpdateStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateStatusActionPerformed
        if (CheckData()) {

            try {

                String transport
                        = txtChildName.getText() + ","
                        + txtDriverName.getText() + ","
                        + txtPickupTime.getText() + ","
                        + txtDropoffTime.getText() + ","
                        + cmbStatus.getSelectedItem() + ","
                        + txtLocation.getText() + "\n";

                FileTestchild.writeToFile("transport.txt", transport);

                JOptionPane.showMessageDialog(this, "Transportation Saved Successfully");

                ClearData();

            } catch (Exception ex) {

                JOptionPane.showMessageDialog(this,ex.getMessage());

            }
        }
    }//GEN-LAST:event_btnUpdateStatusActionPerformed

