    public boolean CheckData() {

        if (txtChildName.getText().trim().isEmpty()) {
            txtChildName.requestFocus();
            txtChildName.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtChildName.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        if (txtDriverName.getText().trim().isEmpty()) {
            txtDriverName.requestFocus();
            txtDriverName.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtDriverName.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        if (txtLocation.getText().trim().isEmpty()) {
            txtLocation.requestFocus();
            txtLocation.setBorder(BorderFactory.createLineBorder(Color.YELLOW));
            return false;
        } else {
            txtLocation.setBorder(BorderFactory.createLineBorder(Color.GRAY));
        }

        JOptionPane.showMessageDialog(this,
                "Transportation Status Updated Successfully");

        return true;
    }

